package doctor

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/Fraction-Roga-i-Kopyta/hypomnema/internal/memindex"
	"github.com/Fraction-Roga-i-Kopyta/hypomnema/internal/native"
)

// globalImport is the line that makes the global index visible in pull-only
// mode: the harness loads only the project MEMORY.md, never the global store.
const globalImport = "@~/.claude/memory-global/MEMORY.md"

// checkGlobalIndex verifies the global store's MEMORY.md is the one memoryctl
// generates, and — in pull-only mode, where prompts inject nothing — that the
// user CLAUDE.md imports it. Both failures are silent otherwise: the Stop
// hook leaves a foreign index untouched every turn, and a missing import
// just hides the global store.
func checkGlobalIndex(claudeDir string) Check {
	const name = "global_index"
	gdir := native.GlobalMemoryDir(filepath.Dir(claudeDir))
	files, err := native.List(gdir)
	if err != nil {
		return Check{Name: name, Status: WARN, Detail: fmt.Sprintf("global store %s unreadable: %v", gdir, err)}
	}
	if len(files) == 0 {
		return Check{Name: name, Status: OK, Detail: "global store is empty"}
	}
	idx := filepath.Join(gdir, "MEMORY.md")
	cur, err := os.ReadFile(idx)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return Check{Name: name, Status: WARN, Detail: fmt.Sprintf("%s missing — run `memoryctl reindex`", idx)}
	case err != nil:
		return Check{Name: name, Status: WARN, Detail: fmt.Sprintf("%s unreadable: %v", idx, err)}
	case !memindex.IsGeneratedGlobal(cur):
		return Check{Name: name, Status: WARN, Detail: fmt.Sprintf(
			"%s was not generated by memoryctl, so the Stop hook never updates it — move it aside and run `memoryctl reindex`", idx)}
	}
	listed := strings.Count(string(cur), "\n- [")
	detail := fmt.Sprintf("%d of %d global facts listed", listed, len(files))
	if pullOnly(claudeDir) {
		claudeMD, _ := os.ReadFile(filepath.Join(claudeDir, "CLAUDE.md"))
		if !strings.Contains(string(claudeMD), "memory-global/MEMORY.md") {
			return Check{Name: name, Status: WARN, Detail: fmt.Sprintf(
				"pull-only mode is on but %s does not import the global index — add the line %s", filepath.Join(claudeDir, "CLAUDE.md"), globalImport)}
		}
		detail += "; pull-only, imported from CLAUDE.md"
	}
	return Check{Name: name, Status: OK, Detail: detail}
}

// pullOnly reports HYPOMNEMA_PROMPT_INJECT=off from the process env or from
// settings.json's env block — doctor usually runs from a plain shell that
// does not carry Claude Code's env.
func pullOnly(claudeDir string) bool {
	off := func(v string) bool { return strings.EqualFold(strings.TrimSpace(v), "off") }
	if off(os.Getenv("HYPOMNEMA_PROMPT_INJECT")) {
		return true
	}
	data, err := os.ReadFile(filepath.Join(claudeDir, "settings.json"))
	if err != nil {
		return false
	}
	var s struct {
		Env map[string]string `json:"env"`
	}
	if json.Unmarshal(data, &s) != nil {
		return false
	}
	return off(s.Env["HYPOMNEMA_PROMPT_INJECT"])
}
