// Package memindex renders a native MEMORY.md index — the table-of-contents
// the harness injects from <project>/memory/MEMORY.md. v2 owns this file: v1
// generated it from the v1 tree with ../../../.claude/memory links, but native
// files are flat siblings of MEMORY.md, so links are bare slugs.
package memindex

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Fraction-Roga-i-Kopyta/hypomnema/internal/native"
)

// DefaultMaxBytes bounds the rendered index. The harness truncates a native
// MEMORY.md over ~24.4KB and warns; staying under keeps the whole index
// loadable.
const DefaultMaxBytes = 24_000

// MaxLines bounds the rendered index by lines: the harness stops reading a
// native MEMORY.md after 200 lines, whatever its size.
const MaxLines = 200

// descCap bounds each description so one long entry can't dominate the index;
// MEMORY.md is a table of contents, not the content itself.
const descCap = 120

// Render builds the MEMORY.md body for the given native files. Links are
// sibling-relative (bare slug). Output never exceeds maxBytes or MaxLines and
// always ends on a complete line. Entries are ordered by indexOrder; once the
// budget is reached the rest are dropped and a closing note says how many,
// with the recall command that still finds them.
func Render(files []native.MemFile, maxBytes int) string {
	return render("# Memory Index\n", files, maxBytes, func(f native.MemFile) string { return f.Slug })
}

// globalHeader opens every generated global index; WriteGlobal treats a
// MEMORY.md that starts with it as its own.
const globalHeader = "# Global Memory Index\n"

// IsGeneratedGlobal reports whether content is a global index memoryctl
// generated (or an empty file it may take over).
func IsGeneratedGlobal(content []byte) bool {
	return strings.TrimSpace(string(content)) == "" || strings.HasPrefix(string(content), globalHeader)
}

// ErrForeignIndex reports a global MEMORY.md that memoryctl did not generate.
var ErrForeignIndex = errors.New("MEMORY.md was not generated by memoryctl; left untouched")

// RenderGlobal builds the index of the global store. The harness never loads
// that store and it is no project's sibling, so each fact links by absolute
// path: the model can Read it from any project. Written beside the global
// facts; a user who turns off UserPromptSubmit injection (pull-only mode)
// imports it from CLAUDE.md so the global store stays visible.
func RenderGlobal(files []native.MemFile, maxBytes int) string {
	const header = globalHeader +
		"Facts that apply in every project. Read a file when its description fits the task.\n"
	return render(header, files, maxBytes, func(f native.MemFile) string {
		if f.Path != "" {
			return f.Path
		}
		return f.Slug
	})
}

func render(header string, files []native.MemFile, maxBytes int, link func(native.MemFile) string) string {
	files = indexOrder(files)
	var b strings.Builder
	b.WriteString(header)
	lines := strings.Count(header, "\n")
	for i, f := range files {
		name := f.Name
		if name == "" {
			name = strings.TrimSuffix(f.Slug, ".md")
		}
		line := fmt.Sprintf("- [%s](%s) — %s\n", name, link(f), truncate(f.Description, descCap))
		// Every entry but the last must leave room for the note that would
		// follow if the next one does not fit.
		reserve, reserveLines := 0, 0
		if i < len(files)-1 {
			reserve, reserveLines = len(truncationNote(len(files)-i-1)), noteLines
		}
		if b.Len()+len(line)+reserve > maxBytes || lines+1+reserveLines > MaxLines {
			// The reserve guarantees room after any written entry; only a
			// budget too small for the header itself leaves the note out.
			if note := truncationNote(len(files) - i); b.Len()+len(note) <= maxBytes {
				b.WriteString(note)
			}
			break
		}
		b.WriteString(line)
		lines++
	}
	return b.String()
}

// noteLines is the line count truncationNote adds (a blank line, then the note).
const noteLines = 2

// truncationNote closes an index cut at its budget. It is never longer than
// the reserve render keeps for it: a smaller hidden count never adds digits.
func truncationNote(hidden int) string {
	return fmt.Sprintf("\n_%d more not listed — find them with `memoryctl recall \"<words>\"`._\n", hidden)
}

// indexOrder sorts a copy of files so the budget cut drops the least likely
// to matter: pinned facts first, then the freshest (later of created and
// modified), slug as a stable tie-break. native.List yields alphabetical
// order, which silently hid every fact past the budget's letter.
func indexOrder(files []native.MemFile) []native.MemFile {
	out := append([]native.MemFile(nil), files...)
	fresh := func(f native.MemFile) string {
		if f.Modified > f.Created {
			return f.Modified
		}
		return f.Created
	}
	sort.SliceStable(out, func(i, j int) bool {
		pi, pj := out[i].Status == "pinned", out[j].Status == "pinned"
		if pi != pj {
			return pi
		}
		if fi, fj := fresh(out[i]), fresh(out[j]); fi != fj {
			return fi > fj
		}
		return out[i].Slug < out[j].Slug
	})
	return out
}

// truncate caps s at n runes (not bytes), appending an ellipsis so the cut is
// visible. Rune-safe so multi-byte (Cyrillic, CJK) descriptions never split a
// codepoint.
func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return strings.TrimRight(string(r[:n]), " ") + "…"
}

// Write atomically replaces <dir>/MEMORY.md with content. Temp-file +
// rename (invariant I3) so a torn write never leaves the harness a
// half-written index to inject.
func Write(dir, content string) error {
	tmp, err := os.CreateTemp(dir, ".MEMORY.*.tmp")
	if err != nil {
		return fmt.Errorf("memindex.Write: create temp: %w", err)
	}
	tmpPath := tmp.Name()
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		os.Remove(tmpPath)
		return fmt.Errorf("memindex.Write: write temp: %w", err)
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpPath)
		return fmt.Errorf("memindex.Write: close temp: %w", err)
	}
	if err := os.Rename(tmpPath, filepath.Join(dir, "MEMORY.md")); err != nil {
		os.Remove(tmpPath)
		return fmt.Errorf("memindex.Write: rename: %w", err)
	}
	return nil
}

// WriteGlobal writes the global store's index like Write, but only over a
// MEMORY.md it generated itself (globalHeader), an empty one, or none. The
// global store is not hypomnema's alone — the user or the model may keep
// their own pointers there — and the Stop hook runs every turn, so a foreign
// file is left as is and ErrForeignIndex returned.
func WriteGlobal(dir, content string) error {
	cur, err := os.ReadFile(filepath.Join(dir, "MEMORY.md"))
	switch {
	case errors.Is(err, fs.ErrNotExist):
	case err != nil:
		return fmt.Errorf("memindex.WriteGlobal: %w", err)
	case !IsGeneratedGlobal(cur):
		return fmt.Errorf("%s: %w", filepath.Join(dir, "MEMORY.md"), ErrForeignIndex)
	}
	return Write(dir, content)
}
