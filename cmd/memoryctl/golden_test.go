package main

import (
	"flag"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"testing"

	"github.com/Fraction-Roga-i-Kopyta/hypomnema/internal/native"
)

// The golden contract between `memoryctl stats --json` and the memboard mod:
// each case runs the CLI on a fixed fixture and its normalized JSON is a
// typed constant in mods/memboard/hooks/fixtures.gen.ts, which the mod's own
// tests import — both sides test one JSON shape. Regenerate with
//
//	go test ./cmd/memoryctl -run Golden -update
var updateGolden = flag.Bool("update", false, "rewrite mods/memboard/hooks/fixtures.gen.ts from the golden cases")

const (
	goldenPath   = "../../mods/memboard/hooks/fixtures.gen.ts"
	goldenHeader = "// Code generated by go test ./cmd/memoryctl -run Golden -update. DO NOT EDIT.\n\n" +
		"import type { StatsReport } from './memoryctl'\n"
)

type goldenCase struct {
	name string                                       // the exported TS constant
	run  func(t *testing.T, root string) (out string) // raw CLI stdout for a world under root
}

// goldenCases is the ordered content of fixtures.gen.ts.
var goldenCases = []goldenCase{
	{"STATS_SESSION", goldenSession},
	{"STATS_FACT", goldenFact},
	{"STATS_PROJECT", goldenProject},
}

// goldenWorld is statsWorld plus marks of every display form on alpha
// (hide:<project>, less, task:rewrite).
func goldenWorld(t *testing.T, root string) map[string]string {
	t.Helper()
	env, _ := statsWorld(t, root)
	for _, d := range []string{"less", "hide", "rewrite"} {
		if _, errOut, code := run(t, env, "mark", "alpha", d); code != 0 {
			t.Fatalf("mark alpha %s: exit=%d stderr=%s", d, code, errOut)
		}
	}
	return env
}

func goldenSession(t *testing.T, root string) string {
	env := goldenWorld(t, root)
	_, out := runStatsJSON(t, env, "--scope", "session", "--session", "s1")
	return out
}

func goldenFact(t *testing.T, root string) string {
	env := goldenWorld(t, root)
	_, out := runStatsJSON(t, withEnv(env, "HYPOMNEMA_SESSION_ID", "s1"), "--scope", "fact", "alpha")
	return out
}

func goldenProject(t *testing.T, root string) string {
	env := goldenWorld(t, root)
	_, out := runStatsJSON(t, env, "--scope", "project")
	return out
}

// normalizeGolden replaces the per-run temp root in both spellings it takes
// in the JSON — as a path (/HOME) and sanitized into a store tag (-HOME) —
// longest first, so the output is identical across runs and machines.
func normalizeGolden(out, root string) string {
	forms := []struct{ from, to string }{
		{root, "/HOME"},
		{native.SanitizePath(root), "-HOME"},
	}
	sort.SliceStable(forms, func(i, j int) bool { return len(forms[i].from) > len(forms[j].from) })
	for _, f := range forms {
		out = strings.ReplaceAll(out, f.from, f.to)
	}
	return out
}

// goldenRun runs case c in a fresh root; it returns the normalized JSON and
// the root it ran under.
func goldenRun(t *testing.T, c goldenCase) (norm, root string) {
	t.Helper()
	root = statsRoot(t)
	return normalizeGolden(c.run(t, root), root), root
}

func goldenJSON(t *testing.T, c goldenCase) string {
	t.Helper()
	norm, _ := goldenRun(t, c)
	return norm
}

func goldenBlock(name, json string) string {
	return "export const " + name + ": StatsReport = " + strings.TrimRight(json, "\n") + "\n"
}

func renderGolden(t *testing.T) string {
	t.Helper()
	var b strings.Builder
	b.WriteString(goldenHeader)
	for _, c := range goldenCases {
		b.WriteString("\n")
		b.WriteString(goldenBlock(c.name, goldenJSON(t, c)))
	}
	return b.String()
}

var goldenWriteOnce sync.Once

// extractGolden returns the block of constant name from the file text: from
// its `export const` line through the first closing brace at column 0.
func extractGolden(text, name string) (string, bool) {
	start := "export const " + name + ": StatsReport = {"
	lines := strings.Split(text, "\n")
	for i, ln := range lines {
		if ln != start {
			continue
		}
		for j := i + 1; j < len(lines); j++ {
			if lines[j] == "}" {
				return strings.Join(lines[i:j+1], "\n") + "\n", true
			}
		}
		return "", false
	}
	return "", false
}

func checkGolden(t *testing.T, name string) {
	t.Helper()
	var c goldenCase
	for _, gc := range goldenCases {
		if gc.name == name {
			c = gc
		}
	}
	if c.run == nil {
		t.Fatalf("no golden case %s", name)
	}
	if *updateGolden {
		goldenWriteOnce.Do(func() {
			if err := os.MkdirAll(filepath.Dir(goldenPath), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(goldenPath, []byte(renderGolden(t)), 0o644); err != nil {
				t.Fatal(err)
			}
		})
	}
	raw, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate: go test ./cmd/memoryctl -run Golden -update)", goldenPath, err)
	}
	text := string(raw)
	if !strings.HasPrefix(text, goldenHeader) {
		t.Fatalf("%s: header drifted (regenerate: go test ./cmd/memoryctl -run Golden -update)", goldenPath)
	}
	want, ok := extractGolden(text, name)
	if !ok {
		t.Fatalf("%s: no constant %s (regenerate: go test ./cmd/memoryctl -run Golden -update)", goldenPath, name)
	}
	if got := goldenBlock(name, goldenJSON(t, c)); got != want {
		t.Fatalf("%s drifted from %s (regenerate: go test ./cmd/memoryctl -run Golden -update)\n--- got\n%s--- want\n%s",
			name, goldenPath, got, want)
	}
}

func TestGolden_Session(t *testing.T) { checkGolden(t, "STATS_SESSION") }

func TestGolden_Fact(t *testing.T) { checkGolden(t, "STATS_FACT") }

func TestGolden_Project(t *testing.T) { checkGolden(t, "STATS_PROJECT") }

// TestGolden_StableAcrossRuns: two runs in different temp roots give
// byte-identical normalized JSON, and no temp path survives normalization.
func TestGolden_StableAcrossRuns(t *testing.T) {
	for _, c := range goldenCases {
		a, rootA := goldenRun(t, c)
		b, rootB := goldenRun(t, c)
		if rootA == rootB {
			t.Fatal("runs must use different roots")
		}
		if a != b {
			t.Fatalf("%s differs across runs:\n--- run 1\n%s--- run 2\n%s", c.name, a, b)
		}
		for _, leak := range []string{rootA, native.SanitizePath(rootA)} {
			if strings.Contains(a, leak) {
				t.Fatalf("%s keeps temp root %q:\n%s", c.name, leak, a)
			}
		}
		if !strings.Contains(a, "/HOME/") || !strings.Contains(a, "-HOME-work-proj") {
			t.Fatalf("%s: placeholders missing:\n%s", c.name, a)
		}
	}
}
